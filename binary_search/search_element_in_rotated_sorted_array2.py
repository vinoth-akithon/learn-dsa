"""
Given the rotated sorted array with duplicate elements.
"""



def optimal_approach(arr: list[int], t: int) -> bool:
    """
        - Using binary search on rotated sorted array (handling duplicates)
            - If all the pointers holding the same values, we cannot conclude which half is sorted, so we need to move pointers one step forward in each direction

        - Complexity Analysis:
            - Time -> O(n) because if most of the elements are duplicate in the given array require moving the pointer one step only instead of cutting half.
            - Space -> O(1)
    """
    n = len(arr)
    s = 0
    e = n-1

    while (s <= e):
        m = s + (e-s)//2

        if arr[m] == t:
            return True
        
        if arr[s] == arr[m] == arr[e]:
            s += 1
            e -= 1

        elif arr[s] <= arr[m]:
            if arr[s] <= t < arr[m]:
                e = m - 1
            else:
                s = m + 1
        else:
            if arr[m] < t <= arr[e]:
                s = m + 1
            else:
                e = m -1

    return False


